// Feats: sixty-three deeds the expedition can be remembered for. Each grants a title to wear and a small
// perk that lasts for good. A feat measures progress as [have, need] from what the record holds.
import type { SkillStats } from './skills.ts';

/** What a feat can look at: the record's tallies and the lasting progress around it. */
export interface FeatCtx {
  tally: Record<string, number>;
  day: number;
  renown: number;
  mastery: Record<string, number>;
  keystones: number;
  bosses: Record<string, number>;
  realmBest: Record<string, number>;
  codexDone: number;
  coins: number;
  shelved: number;
}
export interface Feat {
  id: string;
  name: string;
  /** Worn as "the Unbroken" and the like. */
  title: string;
  text: string;
  group: 'Hunting' | 'Great foes' | 'Wayfaring' | 'Survival' | 'Making' | 'Arms' | 'Renown';
  measure: (c: FeatCtx) => [number, number];
  perk: Partial<SkillStats>;
  perkText: string;
}

const sum = (c: FeatCtx, prefix: string) =>
  Object.entries(c.tally).reduce((n, [k, v]) => (k.startsWith(prefix) ? n + v : n), 0);
const distinct = (c: FeatCtx, prefix: string) =>
  Object.keys(c.tally).filter((k) => k.startsWith(prefix) && c.tally[k] > 0).length;
const all = (c: FeatCtx, prefix: string, ids: string[]): [number, number] => [
  ids.filter((id) => (c.tally[prefix + id] ?? 0) > 0).length,
  ids.length,
];
const at = (have: number, need: number): [number, number] => [Math.min(have, need), need];

