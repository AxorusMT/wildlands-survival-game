// Every creature: how tough it is, how it moves and fights, and what it leaves behind.
import { SETTLERS } from './town.ts';

/** How a creature gets around. Walkers keep to floors, fliers and floaters hover, hoppers bounce. */
export type MobMove = 'walker' | 'flier' | 'floater' | 'hopper';
export interface MobSpec {
  name: string;
  hp: number;
  /** Bite or contact damage. */
  damage: number;
  /** Wandering and chasing speed, world pixels per second. */
  speed: [number, number];
  move: MobMove;
  /** Distance at which it notices the player (0 for creatures that never attack). */
  sight: number;
  /** Reach of its melee attack. */
  reach: number;
  /** Seconds between attacks. */
  cooldown: number;
  defense?: number;
  /** Ranged attack: projectile, range, speed, damage, and how many at once. */
  ranged?: {
    projectile: string;
    range: number;
    speed: number;
    damage: number;
    count?: number;
    spread?: number;
  };
  /** Loot: item, min, max, chance. */
  loot: [string, number, number, number][];
  /** Seconds before a slain creature returns to its home. */
  respawn: number;
  /** Disease its bite may pass on. */
  disease?: [string, number];
  /** Sound family (sfx.ts voices). */
  voice?: string;
  /** Wakes only at night on the surface. */
  night?: boolean;
  boss?: boolean;
}
const L = (item: string, min: number, max = min, chance = 1): [string, number, number, number] => [
  item,
  min,
  max,
  chance,
];

